"""
place_srams.py - write a LibreLane MACRO_PLACEMENT_CFG for every
sky130_sram_2kbyte_1rw1r_32x512_8 instance found in a synthesized netlist.

The SRAM instance names are created deep inside the Chisel hierarchy and
flattened by Yosys, so they are read back from the netlist instead of being
hard-coded.  Macros are placed in rows along the bottom of the core area
(left -> right, bottom -> top), grouped by bank so that the four 32-bit
slices of one 128-bit word sit next to each other.

usage:
  place_srams.py --netlist 'runs/<tag>/*-yosys-synthesis/<top>.nl.v' \
                 --config flow/soc/config.yaml --out flow/soc/macro_placement.cfg
"""
import argparse
import glob
import math
import re
import sys

MACRO = "sky130_sram_2kbyte_1rw1r_32x512_8"
MACRO_W = 683.10   # um, from the macro LEF (SIZE 683.1 BY 416.54)
MACRO_H = 416.54


def natural_key(s):
    return [int(t) if t.isdigit() else t for t in re.split(r"(\d+)", s)]


def find_instances(netlist):
    txt = open(netlist, encoding="utf8").read()
    # instance name may be an escaped identifier: \a.b[0].c  (terminated by space)
    rx = re.compile(rf"^\s*{MACRO}\s+(\\\S+|[A-Za-z_][A-Za-z0-9_$]*)\s*\(", re.M)
    names = [m.group(1) for m in rx.finditer(txt)]
    return [n[1:] if n.startswith("\\") else n for n in names]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--netlist", required=True, help="netlist file or glob")
    ap.add_argument("--core", nargs=4, type=float, metavar=("X0", "Y0", "X1", "Y1"),
                    help="core area; default: CORE_AREA (or DIE_AREA) from --config")
    ap.add_argument("--config", help="LibreLane config.yaml to read CORE_AREA/DIE_AREA from")
    ap.add_argument("--out", required=True)
    ap.add_argument("--margin", type=float, default=40.0, help="distance from core edge (um)")
    ap.add_argument("--hgap", type=float, default=60.0, help="horizontal gap between macros (um)")
    ap.add_argument("--vgap", type=float, default=60.0, help="vertical gap between rows (um)")
    ap.add_argument("--flip-odd-rows", action="store_true",
                    help="mirror every second row (FS) so rows share power/pin edges")
    a = ap.parse_args()

    files = sorted(glob.glob(a.netlist))
    if not files:
        sys.exit(f"[place_srams] netlist not found: {a.netlist}")
    insts = sorted(find_instances(files[-1]), key=natural_key)
    if not insts:
        sys.exit(f"[place_srams] no {MACRO} instances in {files[-1]}")

    if a.core is None:
        if not a.config:
            sys.exit("[place_srams] need --core or --config")
        txt = open(a.config, encoding="utf8").read()

        def area(key):  # tiny parser: "KEY: [x0, y0, x1, y1]"  (no PyYAML needed)
            m = re.search(rf"^{key}:\s*\[([^\]]*)\]", txt, re.M)
            return [float(v) for v in m.group(1).split(",")] if m else None

        if area("CORE_AREA"):
            a.core = area("CORE_AREA")
        elif area("DIE_AREA"):  # Classic flow: core = die minus a small margin
            d = area("DIE_AREA")
            a.core = [d[0] + 10, d[1] + 10, d[2] - 10, d[3] - 10]
        else:
            sys.exit("[place_srams] no CORE_AREA/DIE_AREA in config")
    x0, y0, x1, y1 = a.core
    usable_w = (x1 - x0) - 2 * a.margin
    cols = max(1, int((usable_w + a.hgap) // (MACRO_W + a.hgap)))
    if cols >= 4:
        cols -= cols % 4   # keep the 4 slices of a 128-bit bank on one row
    rows = math.ceil(len(insts) / cols)
    block_h = rows * MACRO_H + (rows - 1) * a.vgap
    if y0 + a.margin + block_h > y1 - a.margin:
        sys.exit(f"[place_srams] {len(insts)} macros need {rows} rows "
                 f"({block_h:.0f} um) - core area too small, enlarge DIE/CORE_AREA")
    # centre the macro block horizontally
    used_w = cols * MACRO_W + (cols - 1) * a.hgap
    xs = x0 + a.margin + (usable_w - used_w) / 2

    lines = [f"# generated by place_srams.py from {files[-1]}",
             f"# {len(insts)} x {MACRO}, grid {cols} cols x {rows} rows",
             "# instance  x(um)  y(um)  orientation"]
    for i, name in enumerate(insts):
        r, c = divmod(i, cols)
        x = xs + c * (MACRO_W + a.hgap)
        y = y0 + a.margin + r * (MACRO_H + a.vgap)
        orient = "FS" if (a.flip_odd_rows and r % 2) else "N"
        lines.append(f"{name} {x:.2f} {y:.2f} {orient}")
    with open(a.out, "w") as f:
        f.write("\n".join(lines) + "\n")

    top_of_block = y0 + a.margin + block_h
    print(f"[place_srams] {len(insts)} SRAM macros -> {a.out}")
    print(f"[place_srams] grid {cols} x {rows}, macro block occupies "
          f"y = {y0 + a.margin:.0f} .. {top_of_block:.0f} um")
    print(f"[place_srams] std-cell area left above macros: "
          f"{(x1 - x0) * (y1 - top_of_block) / 1e6:.2f} mm^2")


if __name__ == "__main__":
    main()
