"""
prepare_rtl.py - post-process the monolithic SystemVerilog emitted by
CoralNPU's Chisel generator so it can be implemented with SKY130:

  1. remove the technology black boxes `Sram` and `ClockGate`
     (replaced by rtl/sky130/Sram_sky130.v and rtl/sky130/ClockGate_sky130.v)
  2. rename the top module (CoreMiniAxi, CoreMini_ITCM8KB_DTCM8KBAxi, ...)
     to `CoralNPUCore` so the wrapper does not depend on the variant
  3. check that every input port of the core is driven by rtl/soc/coralnpu_soc.v

usage: prepare_rtl.py <emitted.sv> <out.sv> [--top <ModuleName>]
"""
import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPLACED = ["Sram", "ClockGate"]
NEW_TOP = "CoralNPUCore"


def strip_module(src: str, name: str):
    """Remove `module <name> ... endmodule` (first match). Returns (src, found)."""
    rx = re.compile(rf"^[ \t]*module\s+{re.escape(name)}\b.*?^[ \t]*endmodule\b[^\n]*\n?",
                    re.S | re.M)
    m = rx.search(src)
    if not m:
        return src, False
    return src[: m.start()] + f"// [prepare_rtl] module {name} removed (sky130 replacement)\n" + src[m.end():], True


def module_names(src: str):
    return re.findall(r"^[ \t]*module\s+([A-Za-z_][A-Za-z0-9_$]*)", src, re.M)


def module_ports(src: str, name: str):
    """Return dict port -> direction for an ANSI-style module header."""
    m = re.search(rf"^[ \t]*module\s+{re.escape(name)}\s*(#\s*\(.*?\)\s*)?\((.*?)\);", src, re.S | re.M)
    if not m:
        return {}
    ports = {}
    direction = None
    for raw in m.group(2).split(","):
        tok = re.sub(r"//.*", "", raw).strip()
        if not tok:
            continue
        d = re.match(r"(input|output|inout)\b", tok)
        if d:
            direction = d.group(1)
        pname = re.findall(r"([A-Za-z_][A-Za-z0-9_$]*)\s*$", tok)
        if pname and direction:
            ports[pname[0]] = direction
    return ports


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("src")
    ap.add_argument("dst")
    ap.add_argument("--top", default=None, help="top module in the emitted file")
    ap.add_argument("--wrapper", default=os.path.join(ROOT, "rtl", "soc", "coralnpu_soc.v"))
    a = ap.parse_args()

    src = open(a.src, encoding="utf8").read()
    names = module_names(src)
    top = a.top
    if top is None:
        base = os.path.splitext(os.path.basename(a.src))[0]
        top = base if base in names else next((n for n in reversed(names) if n.endswith("Axi")), None)
    if top is None or top not in names:
        sys.exit(f"[prepare_rtl] cannot find top module (found: {names[-5:]})")
    print(f"[prepare_rtl] top module      : {top}  ({len(names)} modules)")

    for name in REPLACED:
        count = 0
        while True:
            src, found = strip_module(src, name)
            if not found:
                break
            count += 1
        print(f"[prepare_rtl] removed {name:10s}: {count} definition(s)")
        if count == 0:
            print(f"[prepare_rtl] WARNING: {name} not found - check the emitted RTL")

    if "import \"DPI-C\"" in src:
        print("[prepare_rtl] WARNING: DPI-C imports remain in the RTL (simulation only code?)")

    src = re.sub(rf"^([ \t]*module\s+){re.escape(top)}\b", rf"\g<1>{NEW_TOP}", src, count=1, flags=re.M)

    header = (
        "// Generated by scripts/prepare_rtl.py from "
        f"{os.path.basename(a.src)} (top {top} -> {NEW_TOP})\n"
    )
    os.makedirs(os.path.dirname(os.path.abspath(a.dst)), exist_ok=True)
    with open(a.dst, "w", encoding="utf8") as f:
        f.write(header + src)
    print(f"[prepare_rtl] wrote           : {a.dst}")

    # --------------------------------------------------------- port check
    ports = module_ports(src, NEW_TOP)
    wrapper = open(a.wrapper, encoding="utf8").read()
    connected = set(re.findall(r"\.(io_[A-Za-z0-9_]+)\s*\(", wrapper))
    missing_in = sorted(p for p, d in ports.items() if d == "input" and p not in connected)
    missing_out = sorted(p for p, d in ports.items() if d == "output" and p not in connected)
    unknown = sorted(p for p in connected if ports and p not in ports)
    print(f"[prepare_rtl] core ports      : {len(ports)} "
          f"({sum(1 for d in ports.values() if d == 'input')} in / "
          f"{sum(1 for d in ports.values() if d == 'output')} out)")
    if missing_out:
        print(f"[prepare_rtl] unconnected outputs (ok, e.g. debug trace): {len(missing_out)}")
    if unknown:
        print("[prepare_rtl] ERROR: wrapper connects ports the core does not have:")
        for p in unknown:
            print("    ", p)
    if missing_in:
        print("[prepare_rtl] ERROR: core inputs not driven by coralnpu_soc.v:")
        for p in missing_in:
            print("    ", p)
    if unknown or missing_in:
        sys.exit(1)
    print("[prepare_rtl] port check      : OK")


if __name__ == "__main__":
    main()
